import { describe, it, expect } from 'vitest';
import { GeminiProvider } from '@/lib/ai/geminiProvider';
import { CourseMaterialRetrievalService } from '@/lib/context/retrievalService';
import { CourseMaterial } from '@/types';
import { LlmPromptContext } from '@/lib/ai/types';

describe('Feature C & D: Gemini LLM Integration & Course Material Retrieval', () => {
  const provider = new GeminiProvider();
  const retrieval = new CourseMaterialRetrievalService();

  const dummyContext: LlmPromptContext = {
    questionId: 'q-demo-1',
    courseTitle: 'Principles of Economics',
    questionText: 'What is the primary cause of inflation in macroeconomics?',
    options: [
      'Excess growth in the money supply',
      'Decrease in government regulation',
      'Seasonal changes in agricultural yield',
      'Fixed currency exchange pegs',
    ],
    questionType: 'single-choice',
  };

  it('correctly parses and validates a well-formed structured JSON response', () => {
    const rawResponse = JSON.stringify({
      questionId: 'q-demo-1',
      recommendedAnswers: ['Excess growth in the money supply'],
      explanation: 'Monetarist theory demonstrates that sustained inflation results from excess money creation.',
      evidence: 'Friedman stated inflation is always and everywhere a monetary phenomenon.',
      basis: 'course-material',
      uncertaintyReasons: [],
      needsReview: false,
    });

    const res = provider.parseAndValidateRecommendation(rawResponse, dummyContext);

    expect(res.questionId).toBe('q-demo-1');
    expect(res.recommendedAnswers).toEqual(['Excess growth in the money supply']);
    expect(res.basis).toBe('course-material');
    expect(res.needsReview).toBe(false);
  });

  it('rejects hallucinated options that do not exist among the visible options', () => {
    const rawResponse = JSON.stringify({
      questionId: 'q-demo-1',
      recommendedAnswers: ['Non-existent option generated by model hallucination'],
      explanation: 'Some explanation.',
      basis: 'ai-reasoning',
      uncertaintyReasons: [],
      needsReview: false,
    });

    const res = provider.parseAndValidateRecommendation(rawResponse, dummyContext);

    // Hallucinated answer should be rejected, leaving recommendedAnswers empty and needsReview true
    expect(res.recommendedAnswers.length).toBe(0);
    expect(res.basis).toBe('unresolved');
    expect(res.needsReview).toBe(true);
    expect(res.uncertaintyReasons).toBeDefined();
    expect(res.uncertaintyReasons!.some((u) => u.includes('hallucinated'))).toBe(true);
  });

  it('enforces single-choice constraint if model returns multiple answers for single-choice', () => {
    const rawResponse = JSON.stringify({
      questionId: 'q-demo-1',
      recommendedAnswers: [
        'Excess growth in the money supply',
        'Decrease in government regulation',
      ],
      explanation: 'Both could be factors.',
      basis: 'ai-reasoning',
      uncertaintyReasons: [],
      needsReview: false,
    });

    const res = provider.parseAndValidateRecommendation(rawResponse, dummyContext);

    expect(res.recommendedAnswers.length).toBe(1);
    expect(res.recommendedAnswers[0]).toBe('Excess growth in the money supply');
    expect(res.needsReview).toBe(true);
    expect(res.uncertaintyReasons?.some((u) => u.includes('single-choice'))).toBe(true);
  });

  it('handles malformed JSON responses safely without crashing', () => {
    const malformed = '{ questionId: invalid json string ...';

    const res = provider.parseAndValidateRecommendation(malformed, dummyContext);

    expect(res.basis).toBe('unresolved');
    expect(res.needsReview).toBe(true);
    expect(res.uncertaintyReasons?.some((u) => u.includes('Malformed JSON'))).toBe(true);
  });

  it('flags needsReview as true when answer is based on AI reasoning without direct course evidence', () => {
    const rawResponse = JSON.stringify({
      questionId: 'q-demo-1',
      recommendedAnswers: ['Excess growth in the money supply'],
      explanation: 'General economic reasoning.',
      evidence: '', // Missing direct evidence
      basis: 'ai-reasoning',
      uncertaintyReasons: [],
      needsReview: false,
    });

    const res = provider.parseAndValidateRecommendation(rawResponse, dummyContext);

    expect(res.needsReview).toBe(true);
  });

  it('returns unresolved response when Gemini API key is missing without making network calls', async () => {
    const res = await provider.recommendAnswer(dummyContext, '');

    expect(res.recommendations[0].basis).toBe('unresolved');
    expect(res.recommendations[0].needsReview).toBe(true);
    expect(res.recommendations[0].uncertaintyReasons).toContain('API key missing in settings.');
  });

  it('retrieves relevant course material excerpts based on keyword tokens', () => {
    const sampleMaterials: CourseMaterial[] = [
      {
        id: 'mat-1',
        courseId: 'course-econ-101',
        title: 'Lecture 4: Money and Inflation',
        unitTitle: 'Week 4',
        type: 'notes',
        content: `Inflation is defined as a general increase in prices. In modern macroeconomics, excess growth in the money supply relative to economic output is considered the primary driver of persistent price inflation.`,
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      },
      {
        id: 'mat-2',
        courseId: 'course-econ-101',
        title: 'Lecture 1: Consumer Surplus',
        unitTitle: 'Week 1',
        type: 'notes',
        content: `Consumer surplus is the difference between the maximum price a consumer is willing to pay and the actual market price.`,
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      },
    ];

    const excerpts = retrieval.retrieveExcerpts(
      'What is the primary cause of inflation in macroeconomics?',
      ['Excess growth in the money supply'],
      sampleMaterials
    );

    expect(excerpts.length).toBeGreaterThan(0);
    expect(excerpts[0].materialTitle).toBe('Lecture 4: Money and Inflation');
    expect(excerpts[0].excerpt).toContain('excess growth in the money supply');
  });

  it('returns empty excerpts when no materials match question tokens', () => {
    const sampleMaterials: CourseMaterial[] = [
      {
        id: 'mat-2',
        courseId: 'course-econ-101',
        title: 'Lecture 1: Consumer Surplus',
        type: 'notes',
        content: `Consumer surplus is the difference between willingness to pay and actual price.`,
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      },
    ];

    const excerpts = retrieval.retrieveExcerpts(
      'Calculate the thermodynamic entropy of an ideal gas',
      ['PV=nRT'],
      sampleMaterials
    );

    expect(excerpts.length).toBe(0);
  });
});

describe('GrokProvider & Dual Provider Registry', () => {
  it('correctly resolves providers from getLlmProvider registry', async () => {
    const { getLlmProvider, GeminiProvider, GrokProvider } = await import('@/lib/ai');
    const gemini = getLlmProvider('gemini');
    const grok = getLlmProvider('grok');

    expect(gemini).toBeInstanceOf(GeminiProvider);
    expect(gemini.id).toBe('gemini');

    expect(grok).toBeInstanceOf(GrokProvider);
    expect(grok.id).toBe('grok');
  });

  it('GrokProvider returns error recommendation when API key is missing', async () => {
    const { GrokProvider } = await import('@/lib/ai/grokProvider');
    const grok = new GrokProvider();

    const res = await grok.recommendAnswer(
      {
        questionId: 'q-test',
        courseTitle: 'Economics',
        questionText: 'What is demand?',
        options: ['Desire backed by ability to pay', 'Desire without money'],
        questionType: 'single-choice',
      },
      '',
      'grok-2-latest'
    );

    expect(res.error).toBe('API key missing in settings.');
    expect(res.recommendations[0].needsReview).toBe(true);
  });

  it('GrokProvider testConnection rejects empty API key', async () => {
    const { GrokProvider } = await import('@/lib/ai/grokProvider');
    const grok = new GrokProvider();
    const testRes = await grok.testConnection('', 'grok-2-latest');
    expect(testRes.success).toBe(false);
    expect(testRes.message).toContain('API key is required');
  });
});
